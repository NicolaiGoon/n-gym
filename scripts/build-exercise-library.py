#!/usr/bin/env python3
"""
Builds the bundled exercise library from free-exercise-db (public domain, Unlicense):
https://github.com/yuhonas/free-exercise-db

Writes src/data/exercise-library.json, one small WebP picture per exercise in
assets/exercises/, and src/data/exercise-images.ts, which maps library ids to those pictures.
Needs Pillow. Run from the repository root: python3 scripts/build-exercise-library.py
"""
import io
import json
import os
import re
import urllib.request

from PIL import Image

SOURCE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main'
# Stretches and cardio aren't logged as sets, so they stay out.
CATEGORIES = {'strength', 'powerlifting', 'olympic weightlifting', 'strongman', 'plyometrics'}
GROUPS = {
    'chest': 'chest',
    'lats': 'back', 'middle back': 'back', 'lower back': 'back', 'traps': 'back',
    'shoulders': 'shoulders', 'biceps': 'biceps', 'triceps': 'triceps', 'forearms': 'forearms',
    'abdominals': 'abs',
    'quadriceps': 'legs', 'hamstrings': 'legs', 'adductors': 'legs', 'abductors': 'legs',
    'glutes': 'glutes', 'calves': 'calves', 'neck': 'other',
}
EQUIPMENT = {
    'body only': 'bodyweight', 'kettlebells': 'kettlebell', 'bands': 'band', 'e-z curl bar': 'ez bar',
    'other': None, None: None,
}
WIDTH = 240


def fetch(path):
    with urllib.request.urlopen(f'{SOURCE}/{path}') as response:
        return response.read()


def main():
    source = json.loads(fetch('dist/exercises.json'))
    os.makedirs('assets/exercises', exist_ok=True)
    library = []
    for item in sorted(source, key=lambda e: e['name'].lower()):
        if item['category'] not in CATEGORIES or not item['primaryMuscles']:
            continue
        slug = re.sub(r'[^a-z0-9]+', '-', item['id'].lower()).strip('-')
        image = f'assets/exercises/{slug}.webp'
        if not os.path.exists(image) and item['images']:
            picture = Image.open(io.BytesIO(fetch(f"exercises/{item['images'][0]}"))).convert('RGB')
            picture.thumbnail((WIDTH, WIDTH * 2))
            picture.save(image, 'WEBP', quality=50, method=6)
        library.append({
            'id': slug,
            'name': item['name'].strip(),
            'muscleGroup': GROUPS[item['primaryMuscles'][0]],
            'primaryMuscles': item['primaryMuscles'],
            'secondaryMuscles': item['secondaryMuscles'],
            'equipment': EQUIPMENT.get(item['equipment'], item['equipment']),
            'mechanic': item['mechanic'],
            'level': item['level'],
            'instructions': item['instructions'],
            'image': os.path.exists(image),
        })
    with open('src/data/exercise-library.json', 'w') as f:
        json.dump(library, f, ensure_ascii=False, separators=(',', ':'))
    with open('src/data/exercise-images.ts', 'w') as f:
        f.write('// Generated by scripts/build-exercise-library.py. Do not edit.\n')
        f.write('export const EXERCISE_IMAGES: Record<string, number> = {\n')
        for e in library:
            if e['image']:
                f.write(f"  '{e['id']}': require('../../assets/exercises/{e['id']}.webp'),\n")
        f.write('};\n')
    print(len(library), 'exercises')


if __name__ == '__main__':
    main()
